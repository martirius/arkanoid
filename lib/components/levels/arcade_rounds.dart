final List<LevelDefinition> arcadeRounds1To32 = List.unmodifiable([
  for (var index = 0; index < _layouts.length; index++)
    _createRound(index + 1, _layouts[index]),
]);

const _fieldCycle = [
  FieldType.blue,
  FieldType.green,
  FieldType.electricBlue,
  FieldType.electricRed,
];

LevelDefinition _createRound(int roundNumber, String layout) {
  final cells = layout.replaceAll('\n', '');
  if (cells.length != LevelDefinition.rowCount * LevelDefinition.columnCount) {
    throw StateError('Invalid arcade layout for round $roundNumber');
  }

  final models = [
    for (final cell in cells.split('')) _modelFor(cell.toUpperCase()),
  ];

  return LevelDefinition(
    roundNumber: roundNumber,
    fieldType: _fieldCycle[(roundNumber - 1) % _fieldCycle.length],
    rows: [
      for (var row = 0; row < LevelDefinition.rowCount; row++)
        [
          for (var column = 0; column < LevelDefinition.columnCount; column++)
            switch (models[row * LevelDefinition.columnCount + column]) {
              final model? => BrickSpec(model),
              null => null,
            },
        ],
    ],
  );
}

BrickModel? _modelFor(String cell) => switch (cell) {
      '.' => null,
      'W' => BrickModel.grey,
      'O' => BrickModel.orange,
      'C' => BrickModel.lightBlue,
      'G' => BrickModel.green,
      'R' => BrickModel.red,
      'B' => BrickModel.blue,
      'P' => BrickModel.pink,
      'Y' => BrickModel.yellow,
      'S' => BrickModel.silver,
      'D' => BrickModel.gold,
      _ => throw StateError('Unknown arcade brick code: $cell'),
    };

